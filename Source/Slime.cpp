//*---------------------------------------------------------------------------------------
//*【?】状態の初期化を行う（オブジェクトプール用）
//*
//* [引数]なし
//* [返値]なし
//*----------------------------------------------------------------------------------------
void Slime::ResetForReuse()
{
	// トランスフォームリセット
	mTransform.Reset();	

	// 状態リセット
	m_Runtime.size = 0.0f;
	m_Runtime.speed = 0.0f;
	m_Runtime.splitPhase = SLIME_SPLIT_PHASE::PHASE_0;
}

