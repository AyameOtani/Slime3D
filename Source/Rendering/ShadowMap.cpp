#include "ShadowMap.h"
#include "../Utility.h"


//*---------------------------------------------------------------------------------------
//*【?】コンストラクタ
//* [引数]
//* sizeX : シャドウマップの横幅 
//* sizeY : シャドウマップの縦幅
//*----------------------------------------------------------------------------------------
ShadowMap::ShadowMap(float sizeX, float sizeY)
	: m_ShadowMapHandle(-1)
	, m_SizeX(sizeX)
	, m_SizeY(sizeY)

{

}

//*---------------------------------------------------------------------------------------
//*【?】デストラクタ
//*----------------------------------------------------------------------------------------
ShadowMap::~ShadowMap()
{

}


//*---------------------------------------------------------------------------------------
//*【?】初期化
//*
//* [引数] なし
//* [返値]
//* 初期化成功したか 
//*----------------------------------------------------------------------------------------
bool ShadowMap::Setup()
{
	// シャドウマップを作成する
	m_ShadowMapHandle = MakeShadowMap(m_SizeX, m_SizeY);

	if (m_ShadowMapHandle == -1)
	{
		Helper::Debug::ErrorMessage(L"シャドウマップの作成に失敗しました", L"ShadowMap::Setup");
		return false;
	}

	return true;
}


//*---------------------------------------------------------------------------------------
//*【?】終了
//*
//* [引数] なし
//* [返値] なし
//*----------------------------------------------------------------------------------------
void ShadowMap::Finalize()
{
	if (m_ShadowMapHandle != -1)
	{
		// シャドウマップの削除
		DeleteShadowMap(m_ShadowMapHandle);
		m_ShadowMapHandle = -1;
	}
}


//*---------------------------------------------------------------------------------------
//*【?】シャドウマップへの書き込み - 開始
//* ※ 必ずSetup後に呼んでください
//*
//* [引数] なし
//* [返値] なし
//*----------------------------------------------------------------------------------------
void ShadowMap::ShadowMapWriteBegin()
{
	if (m_ShadowMapHandle != -1)
	{
		ShadowMap_DrawSetup(m_ShadowMapHandle);
	}
}

//*---------------------------------------------------------------------------------------
//*【?】シャドウマップへの書き込み - 終了
//* ※ 必ずSetup後に呼んでください
//*
//* [引数] なし
//* [返値] なし
//*----------------------------------------------------------------------------------------
void ShadowMap::ShadowMapWriteEnd()
{
	if (m_ShadowMapHandle != -1)
	{
		ShadowMap_DrawEnd();
	}
}

//*---------------------------------------------------------------------------------------
//*【?】シャドウマップをバインドする
//* ※ 必ずSetup後に呼んでください
//*
//* [引数] なし
//* [返値] なし
//*----------------------------------------------------------------------------------------
void ShadowMap::ShadowMapBind()
{
	if (m_ShadowMapHandle != -1)
	{
		SetUseShadowMap(0, m_ShadowMapHandle);
	}
}

//*---------------------------------------------------------------------------------------
//*【?】シャドウマップのバインドを解く
//* ※ 必ずSetup後に呼んでください
//*
//* [引数] なし
//* [返値] なし
//*----------------------------------------------------------------------------------------
void ShadowMap::ShadowMapUnbind()
{
	if (m_ShadowMapHandle != -1)
	{
		SetUseShadowMap(0, -1);
	}
}

//*---------------------------------------------------------------------------------------
//*【?】ライトの方向（影を落とす向き）
//* ※ 必ずSetup後に呼んでください
//*
//* [引数] 
//* direction : 方向
//* 
//* [返値] なし
//*----------------------------------------------------------------------------------------
void ShadowMap::SetLightDirection(const VECTOR& direction)
{
	if (m_ShadowMapHandle != -1)
	{
		SetShadowMapLightDirection(m_ShadowMapHandle, direction);
	}
}

//*---------------------------------------------------------------------------------------
//*【?】シャドウマップ描画時の補正深度値を設定する
//*		アクネを防ぐためのものです。
//		補正値を大きくし過ぎると、ピーターパディングを起こすのでいい具合にお願いします。
//* ※ 必ずSetup後に呼んでください
//*
//* [引数] 
//* depth : 補正深度値
//* 
//* [返値] なし
//*----------------------------------------------------------------------------------------
void ShadowMap::SetAdjustDepth(float depth)
{
	if (m_ShadowMapHandle != -1)
	{
		SetShadowMapAdjustDepth(m_ShadowMapHandle, depth);
	}
}


//*---------------------------------------------------------------------------------------
//*【?】シャドウマップの描画範囲を設定
//* ※ 必ずSetup後に呼んでください
//*
//* [引数] 
//* minPosition : 補正深度値
//* maxPosition : 補正深度値
//* 
//* [返値] なし
//*----------------------------------------------------------------------------------------
void ShadowMap::SetDrawArea(const VECTOR& minPosition, const VECTOR& maxPosition)
{
	if (m_ShadowMapHandle != -1)
	{
		SetShadowMapDrawArea(m_ShadowMapHandle, minPosition, maxPosition);
	}
}

//*---------------------------------------------------------------------------------------
//*【?】シャドウマップの描画範囲をリセット
//* ※ 必ずSetup後に呼んでください
//*
//* [引数] なし
//* [返値] なし
//*----------------------------------------------------------------------------------------
void ShadowMap::ResetDrawArea()
{
	if (m_ShadowMapHandle != -1)
	{
		ResetShadowMapDrawArea(m_ShadowMapHandle);
	}
}

//*---------------------------------------------------------------------------------------
//*【?】シャドウマップをテスト描画する
//* ※ 必ずSetup後に呼んでください
//*
//* [引数] 
//* x1 : 
//* y1 : 
//* x2 : 
//* x2 : 
//* 
//* [返値] なし
//*----------------------------------------------------------------------------------------
void ShadowMap::TestDraw(int x1, int y1, int x2, int y2)
{
	if (m_ShadowMapHandle != -1)
	{
		TestDrawShadowMap(m_ShadowMapHandle, x1, y1, x2, y2);
	}
}
