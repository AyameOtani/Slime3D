#include "TitleCamera.h"
#include "Utility.h"
#include <cmath>

//*---------------------------------------------------------------------------------------
//*【コンストラクタ】
//*
//* 注視点・位置・角度の初期値を設定する
//*----------------------------------------------------------------------------------------
TitleCamera::TitleCamera()
    : mTarget(VGet(0.0f, 0.0f, 0.0f))
    , mPosition(VGet(0.0f, 0.0f, 0.0f))
    , mYaw(-DX_PI_F * 0.5f)   // -90度から開始すると、ANGLE_B と同じ位置になる
{
}

//*---------------------------------------------------------------------------------------
//*【デストラクタ】
//*
//* 特に解放するものはない
//*----------------------------------------------------------------------------------------
TitleCamera::~TitleCamera()
{
}

//*---------------------------------------------------------------------------------------
//*【カメラの初期化】
//*
//* [引数]
//* targetPosition : 注視点の基準位置（X・Zを使う）
//*
//* [返値] なし
//*----------------------------------------------------------------------------------------
void TitleCamera::Initialize(const VECTOR& targetPosition)
{
    // 注視点はX・Zを基準位置に合わせ、高さは固定値にする
    mTarget = VGet(targetPosition.x, TitleCameraConfig::kTargetY, targetPosition.z);

    // 初期位置を作って反映する
    RebuildPosition();
    Apply();
}

//*---------------------------------------------------------------------------------------
//*【カメラの更新】
//*
//* [引数] なし
//* [返値] なし
//*----------------------------------------------------------------------------------------
void TitleCamera::Update()
{
    // 水平方向の角度を少しずつ増やし、-π～π の範囲に収める
    mYaw = Helper::Math::WrapRadian(mYaw + TitleCameraConfig::kRotateSpeed);
    // 新しい角度で位置を作り直し、反映する
    RebuildPosition();
    Apply();
}

//*---------------------------------------------------------------------------------------
//*【カメラ位置の再計算】
//*
//* 注視点を中心に、現在の角度の方向へ水平距離だけ離す
//*
//* [引数] なし
//* [返値] なし
//*----------------------------------------------------------------------------------------
void TitleCamera::RebuildPosition()
{
    mPosition = VGet(
        mTarget.x + std::sin(mYaw) * TitleCameraConfig::kRadius,
        TitleCameraConfig::kHeight,
        mTarget.z + std::cos(mYaw) * TitleCameraConfig::kRadius
    );
}

//*---------------------------------------------------------------------------------------
//*【カメラ設定の適用】
//*
//* [引数] なし
//* [返値] なし
//*----------------------------------------------------------------------------------------
void TitleCamera::Apply() const
{
    // 視野角を設定する
    SetupCamera_Perspective(Helper::Math::DegToRad(TitleCameraConfig::kFovDeg));

    // 描画距離を設定する
    SetCameraNearFar(TitleCameraConfig::kNear, TitleCameraConfig::kFar);

    // 位置と注視点を設定する
    SetCameraPositionAndTarget_UpVecY(mPosition, mTarget);
}

//*---------------------------------------------------------------------------------------
//*【カメラ位置の取得】
//*
//* [引数] なし
//* [返値] カメラの位置
//*----------------------------------------------------------------------------------------
VECTOR TitleCamera::GetPosition() const
{
    return mPosition;
}

//*---------------------------------------------------------------------------------------
//*【注視点の取得】
//*
//* [引数] なし
//* [返値] 注視点
//*----------------------------------------------------------------------------------------
VECTOR TitleCamera::GetTarget() const
{
    return mTarget;
}