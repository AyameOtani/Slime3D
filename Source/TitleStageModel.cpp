#include "TitleStageModel.h"

//*---------------------------------------------------------------------------------------
//*【コンストラクタ】
//*
//* 読み込み前の初期状態を設定する
//*----------------------------------------------------------------------------------------
TitleStageModel::TitleStageModel()
    : mStage()
    , loaded(false)
{
}

//*---------------------------------------------------------------------------------------
//*【デストラクタ】
//*
//* Stage のデストラクタで解放されるため、ここでは特に処理しない
//*----------------------------------------------------------------------------------------
TitleStageModel::~TitleStageModel()
{
}

//*---------------------------------------------------------------------------------------
//*【ステージの初期化】
//*
//* [引数] なし
//* [返値] なし
//*----------------------------------------------------------------------------------------
void TitleStageModel::Initialize()
{
    // 再初期化時に古いステージが残らないように一度解放する
    if (loaded)
    {
        mStage.Finalize();
        loaded = false;
    }

    // 表示位置を設定する
    const VECTOR position = VGet(
        TitleStageConfig::kStagePosX,
        TitleStageConfig::kStagePosY,
        TitleStageConfig::kStagePosZ);

    // ステージを読み込む
    // 読み込みに失敗した場合は描画せず、床の判定もできない状態のままにする
    loaded = mStage.Initialize(
        TitleStageConfig::kStageModelPath,
        TitleStageConfig::kStageScale,
        position);
}

//*---------------------------------------------------------------------------------------
//*【ステージの描画】
//*
//* [引数] なし
//* [返値] なし
//*----------------------------------------------------------------------------------------
void TitleStageModel::Draw()
{
    // 読み込まれていない場合は描画しない
    if (!loaded) return;

    // ステージ本体を描画する
    mStage.Draw();
}

//*---------------------------------------------------------------------------------------
//*【ステージの終了処理】
//*
//* 読み込んだステージを解放する
//*----------------------------------------------------------------------------------------
void TitleStageModel::Finalize()
{
    // 読み込まれている場合のみ解放する
    if (loaded)
    {
        mStage.Finalize();
        loaded = false;
    }
}

//*---------------------------------------------------------------------------------------
//*【読み込み状態の取得】
//*
//* [引数] なし
//* [返値] 読み込めている場合は true
//*----------------------------------------------------------------------------------------
bool TitleStageModel::IsLoaded() const
{
    return loaded;
}