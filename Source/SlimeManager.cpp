#include "SlimeManager.h"

//*---------------------------------------------------------------------------------------
//*【?】コンストラクタ
//*----------------------------------------------------------------------------------------
SlimeManager::SlimeManager()
    : m_pSlimePool()
    , m_SlimeDefinition()
{

}

//*---------------------------------------------------------------------------------------
//*【?】デストラクタ
//*----------------------------------------------------------------------------------------
SlimeManager::~SlimeManager()
{

}

//*---------------------------------------------------------------------------------------
//*【?】初期化処理
//*
//* [引数] なし
//*
//* [返値]
//* true : 成功
//* false : 失敗
//*----------------------------------------------------------------------------------------
bool SlimeManager::Setup()
{
    // 二重にセットアップしない
    if (m_pSlimePool)
    {
        return true;
    }

    //
    // スライムの固定定義データ
    //
    m_SlimeDefinition[UINT_CAST(Slime::SLIME_TYPE::NORMAL)] =
    {
        {
            // 未分裂状態
            { 0.0f, 0.0f, 0.0f },
            
            // １段階目
            { 0.0f, 0.0f, 0.0f },
            
            // ２段階目
            { 0.0f, 0.0f, 0.0f },
            
            // ３段階目
            { 0.0f, 0.0f, 0.0f },
        },
    };

    //////////////////////////////////////////////////////////////////////////////////////////
    //
    // スライムプールのセットアップ
    // 
    //////////////////////////////////////////////////////////////////////////////////////////
    m_pSlimePool = std::make_unique<ObjectPool<Slime>>(
        // 取得時に実行 ******************************************************************************************
        [&](Slime* obj) 
        {
            // 状態の初期化
            obj->ResetForReuse();       

            obj->SetDeleteFlag(false);
            obj->SetActive(true);
        },
        // 返却時に実行 ******************************************************************************************
        [](Slime* obj)
        {
            obj->SetActive(false);
        },
        // 生成時に実行 ******************************************************************************************
        [&]()->Slime*
        {
            Slime* obj = new Slime();
            obj->SetActive(false);
            return obj;
        },
        SLIME_POOL_DEFAULT_CAPACITY,    // 初期生成数
        SLIME_POOL_CAPACITY             // 最大生成数
    );

	return true;
}

//*---------------------------------------------------------------------------------------
//*【?】終了処理
//*
//* [引数] なし
//* [返値] なし
//*----------------------------------------------------------------------------------------
void SlimeManager::Term()
{
    // プールの開放
    m_pSlimePool->clear();
}